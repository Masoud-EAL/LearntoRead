"""Generate the short share pages — wordlink.au/speaking, wordlink.au/clock.

GitHub Pages serves `<name>.html` at `/<name>`, so every short address is a
real file. Each one is a title, a description and a share preview, then a
redirect to the section or game it names — the same shape as the hand-written
solo.html, which is where this pattern came from.

They are generated rather than hand-kept because there are forty of them and
they differ by five strings. Edit SECTIONS and GAMES below, then re-run:

    python3 tools/build-links.py

Then commit the changed pages. Nothing runs this at deploy time — Pages
publishes the repo as it stands, so the generated files are checked in.
"""

