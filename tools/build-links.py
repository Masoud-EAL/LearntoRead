def esc(s):
    return html.escape(s, quote=True)


def stub(slug, dest, title, desc):
    return STUB.format(marker=MARKER, site=SITE, slug=slug, title=title, desc=desc,
                       blurb=desc.split('.')[0] + '.', dest=dest.replace('&', '&amp;'), dest_js=dest)


def settings_for(g):
    """The start screen's controls for this game, or '' for one that has none."""
    game = g['game']
    if game == 'target':
        # The dice game's settings are chips and a rule choice that a link
        # cannot carry, so Play opens the app's own start screen for them.
        return ''
    if game == 'test:level':
        # No settings, on purpose: see the level check in game.html.
        return ''
    rows = []
    if game in MC_CAPABLE:
        on = game not in MC_OFF
        rows.append(
            '      <button type="button" class="mc-toggle-wrap%s" id="gp-mc" aria-pressed="%s">\n'
            '        <span class="mc-switch"></span>\n'
            '        <span><span class="mc-toggle-txt">🔵 Multiple Choice (4 options)</span>\n'
            '        <span class="mc-toggle-sub">Listen and tap, no typing. Good for early readers.</span></span>\n'
            '      </button>\n'
            '      <input type="hidden" name="mc" id="gp-mc-val" value="%s" data-default="%s">\n'
            % (' on' if on else '', 'true' if on else 'false', '1' if on else '0', '1' if on else '0'))
    nums = []
    if not game.startswith('test:'):
        nums.append('        <div><label for="gp-q">Questions</label>\n'
                    '          <input type="number" class="game-input" id="gp-q" name="q" value="10" min="1" max="50" inputmode="numeric" data-default="10"></div>\n')
    nums.append('        <div><label for="gp-t">Seconds each</label>\n'
                '          <input type="number" class="game-input" id="gp-t" name="t" value="%d" min="10" max="120" inputmode="numeric" data-default="%d"></div>\n'
                % (SECS_DEFAULT, SECS_DEFAULT))
    rows.append('      <div class="launch-nums">\n' + ''.join(nums) + '      </div>\n')
    if game in ('translate', 'test:translation'):
        opts = ''.join('          <option value="%s">%s</option>\n' % (v, esc(n)) for v, n in TRANSLATE_LANGS)
        rows.append('      <div class="gp-lang"><label for="gp-lang">Your language</label>\n'
                    '        <select class="game-input" id="gp-lang" name="lang">\n' + opts +
                    '        </select></div>\n')
    return '    <div class="launch-settings">\n' + ''.join(rows) + '    </div>\n'


def related(g, games):
    """Up to four other pages from the same skill, read on round the list from
    this one so that every page is linked from somewhere, not only the first
    few of each skill."""
    def is_test(x):
        return x['game'].startswith('test:')
    if g['skill'] is None or is_test(g):
        pool = [x for x in games if x is not g and (is_test(x) or x['skill'] is None or x['skill'] == g['skill'])]
    else:
        pool = [x for x in games if x is not g and x['skill'] == g['skill'] and not is_test(x)]
    if len(pool) < 4:
        pool += [x for x in games if x is not g and x not in pool and not is_test(x)]
    i = games.index(g)
    pool.sort(key=lambda x: (games.index(x) - i) % len(games))
    return pool[:4]


def ld_json(g, url, image, skill_label):
    data = {
        '@context': 'https://schema.org',
        '@type': 'LearningResource',
        'name': g['name'],
        'headline': g['seo'],
        'description': g['meta'],
        'url': url,
        'image': image,
        'inLanguage': 'en-AU',
        'isAccessibleForFree': True,
        'learningResourceType': 'Game',
        'interactivityType': 'active',
        'educationalLevel': g['level'],
        'teaches': skill_label,
        'keywords': ', '.join(g['good']),
        'audience': {'@type': 'EducationalAudience',
                     'educationalRole': 'student',
                     'audienceType': 'Adults learning to read and write English'},
        'publisher': {'@type': 'Organization', 'name': 'WordLink', 'url': SITE + '/'},
    }
    # json.dumps leaves "</" alone, and a "</script>" inside a string would end
    # the block early.
    return json.dumps(data, ensure_ascii=False, indent=1).replace('</', '<\\/')


def page(g, games):
    slug, game = g['slug'], g['game']
    url = '%s/%s' % (SITE, slug)
    shot_file = os.path.join(ROOT, 'shots', slug + '.jpg')
    has_shot = os.path.exists(shot_file)
    image = '%s/shots/%s.jpg' % (SITE, slug) if has_shot else SITE + '/icon-512.png'
    label, color, glow = SKILLS[g['skill']]
    skill_label = label if g['skill'] else 'Practice'
    # play=1 goes straight to the first question. The dice game is left without
    # it, so Play opens the app's own start screen and the dice settings there.
    play = '' if game == 'target' else '    <input type="hidden" name="play" value="1">\n'
    shot = ('    <figure class="gp-shot"><img src="shots/%s.jpg" width="1200" height="630" loading="lazy"\n'
            '      alt="%s"></figure>\n' % (slug, esc('A question from %s on a phone' % g['name']))
            if has_shot else '')
    return PAGE.format(
        marker=MARKER, seo=esc(g['seo']), meta=esc(g['meta']), url=url, name=esc(g['name']),
        image=image, card='summary_large_image' if has_shot else 'summary',
        ld=ld_json(g, url, image, skill_label),
        color=color, glow=glow, game_attr=esc(game),
        play_input=play,
        skill_label=esc(skill_label + ' · ' + g['level']), emoji=g['emoji'], sub=esc(g['sub']),
        settings=settings_for(g),
        play_label='▶ Open' if game == 'target' else '▶ Play Game',
        about=esc(g['about']), shot=shot,
        how='\n'.join('      <li>%s</li>' % esc(s) for s in g['how']),
        cls=esc(g['cls']).replace('Teacher Game', '<a href="%s">Teacher Game</a>' % TEACHER, 1),
        teacher=TEACHER,
        good='\n'.join('      <li>%s</li>' % esc(s) for s in g['good']),
        more='\n'.join('      <li><a href="%s"><span aria-hidden="true">%s</span> %s</a></li>'
                       % (x['slug'], x['emoji'], esc(x['name'])) for x in related(g, games)),
    )


def load_games():
    with open(os.path.join(ROOT, 'tools', 'game-pages.json'), encoding='utf-8') as f:
        return json.load(f)['games']


def write_file(name, text):
    with open(os.path.join(ROOT, name), 'w', encoding='utf-8') as f:
        f.write(text)
    return name


def main():
    games = load_games()
    dashes = [g['slug'] for g in games if re.search('[–—]', json.dumps(g, ensure_ascii=False))]
    if dashes:
        raise SystemExit('en or em dash in: ' + ', '.join(dashes))
    written = []
    for slug, dest, title, desc in SECTIONS:
        written.append(write_file(slug + '.html', stub(slug, dest, title, desc)))
    for g in games:
        written.append(write_file(g['slug'] + '.html', page(g, games)))
    update_sw(written)
    update_sitemap([g['slug'] for g in games])
    print('wrote %d pages' % len(written))


def update_sw(files):
    """List the short pages in the service worker's OPTIONAL set.

    OPTIONAL rather than CORE: each is cached individually and a failure does
    not block install, which is the right trade for sixty small pages that
    only matter to a learner who opens a shared link offline.
    """
    path = os.path.join(ROOT, 'sw.js')
    with open(path, encoding='utf-8') as f:
        js = f.read()
    # Both forms of each: the file, and the extensionless address Pages serves
    # it at. A shared link is opened as /clock, and an exact-URL cache match
    # will not find that under ./clock.html.
    block = ('  // %s: the short share addresses (/clock, /speaking).\n' % MARKER
             + ''.join("  './%s',\n  './%s',\n" % (f, f[:-5]) for f in sorted(files))
             + '  // /short links\n')
    js = re.sub(r'  // %s[^\n]*\n(?:.*?)  // /short links\n' % re.escape(MARKER),
                lambda m: block, js, count=1, flags=re.S)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(js)


def update_sitemap(slugs):
    """List every game page in sitemap.xml. They are real, indexable pages now,
    unlike the section stubs, which redirect and stay out. The dates are
    placeholders: tools/stamp-sitemap.py sets each from git at deploy time."""
    path = os.path.join(ROOT, 'sitemap.xml')
    with open(path, encoding='utf-8') as f:
        xml = f.read()
    xml = re.sub(r'\n  <!-- %s -->.*?<!-- /game pages -->' % re.escape(MARKER), '', xml, flags=re.S)
    entries = ''.join(
        '  <url>\n    <loc>%s/%s</loc>\n    <changefreq>monthly</changefreq>\n'
        '    <priority>0.7</priority>\n  </url>\n' % (SITE, s) for s in slugs)
    xml = xml.replace('</urlset>', '  <!-- %s -->\n%s  <!-- /game pages -->\n</urlset>' % (MARKER, entries))
    with open(path, 'w', encoding='utf-8') as f:
        f.write(xml)


if __name__ == '__main__':
    main()
