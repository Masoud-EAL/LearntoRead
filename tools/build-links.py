# The two halves of the app have their own palettes; a stub that flashes the
# wrong one before redirecting looks like a broken page.
LIGHT = dict(theme='#4a90d9', bg='#fdf6ec', fg='#2d2a26', accent='#4a90d9',
             muted='#7a6f65', shadow='rgba(74,144,217,.4)')
DARK = dict(theme='#0d0d1a', bg='#0d0d1a', fg='#f0f0ff', accent='#e94560',
            muted='#8888aa', shadow='rgba(233,69,96,.4)')


def write(slug, dest, title, desc, blurb, palette):
    html = PAGE.format(
        marker=MARKER, site=SITE, slug=slug, title=title, desc=desc, blurb=blurb,
        dest=dest.replace('&', '&amp;'), dest_js=dest, dest_url=dest.replace('&', '&amp;'),
        **palette)
    path = os.path.join(ROOT, slug + '.html')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(html)
    return slug + '.html'


def main():
    written = []
    for slug, dest, title, desc in SECTIONS:
        written.append(write(slug, dest, title, desc, desc.split('.')[0] + '.', LIGHT))
    for slug, game, title, blurb in GAMES:
        desc = blurb + TAIL
        written.append(write(slug, 'game.html?mode=solo&game=' + game, title, desc, blurb, DARK))

    # Keep the sitemap and the service worker in step with the pages that
    # actually exist, so a new slug is never half-added.
    slugs = [s for s, *_ in SECTIONS] + [s for s, *_ in GAMES]
    update_sitemap(slugs)
    update_sw(written)
    print('wrote %d pages' % len(written))


def update_sw(files):
    """List the short pages in the service worker's OPTIONAL set.

    OPTIONAL rather than CORE: each is cached individually and a failure does
    not block install, which is the right trade for forty small redirect pages
    that only matter to a learner who opens a shared link offline.
    """
    path = os.path.join(ROOT, 'sw.js')
    with open(path, encoding='utf-8') as f:
        js = f.read()
    block = ('  // %s — the short share addresses (/clock, /speaking).\n' % MARKER
             + ''.join("  './%s',\n" % f for f in sorted(files))
             + '  // /short links\n')
    if MARKER in js:
        js = re.sub(r'  // %s[^\n]*\n(?:.*?)  // /short links\n' % re.escape(MARKER),
                    block, js, flags=re.S)
    else:
        js = js.replace('const OPTIONAL = [\n', 'const OPTIONAL = [\n' + block, 1)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(js)


def update_sitemap(slugs):
    path = os.path.join(ROOT, 'sitemap.xml')
    with open(path, encoding='utf-8') as f:
        xml = f.read()
    entries = ''.join(
        '  <url>\n'
        '    <loc>%s/%s</loc>\n'
        '    <changefreq>monthly</changefreq>\n'
        '    <priority>0.7</priority>\n'
        '  </url>\n' % (SITE, s) for s in slugs)
    block = '  <!-- %s -->\n%s  <!-- /short links -->\n' % (MARKER, entries)
    if '<!-- ' + MARKER + ' -->' in xml:
        xml = re.sub(r'  <!-- %s -->\n.*?  <!-- /short links -->\n' % re.escape(MARKER),
                     block, xml, flags=re.S)
    else:
        xml = xml.replace('</urlset>', block + '</urlset>')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(xml)


if __name__ == '__main__':
    main()
